import fs from "node:fs";
import { test } from "@playwright/test";
import { createE2eUser, loginThroughUi, cleanupE2eUsers } from "../e2e/support/test-user";
import { UserApi } from "../e2e/support/api";

const OUT = process.env.MEASURE_OUT!;
test("network diagnostics", async ({ page }) => {
  const log: string[] = [];
  page.on("response", (r) => { const s = r.status(); if (s >= 400) log.push(`${s} ${r.request().method()} ${r.url().replace(/^https?:\/\/[^/]+/, "").slice(0, 120)}`); });
  page.on("console", (m) => { if (m.type() === "error" && /same key/.test(m.text())) log.push("KEYWARN " + m.text().slice(0, 100) + " @ " + JSON.stringify(m.location())); });
  await cleanupE2eUsers("run").catch(() => {});
  const user = await createE2eUser();
  const api = await UserApi.for(user);
  const { id, branchId } = await api.createProject("Net project");
  await api.putDraft(id, [{ id: "n1", pitch: 60 }, { id: "n2", pitch: 64, start: 480 }]);
  const c1 = await api.commit(branchId, "First");
  await api.putDraft(id, [{ id: "n1", pitch: 60 }, { id: "n2", pitch: 64, start: 480 }, { id: "n3", pitch: 67, start: 960 }]);
  await api.commit(branchId, "Second");
  await api.createBranch(id, "variation", c1.id);
  await page.addInitScript(() => localStorage.setItem("stave-lang", "en"));
  await page.setViewportSize({ width: 1440, height: 900 });
  await loginThroughUi(page, user);
  log.push("--- after login");
  const t0 = Date.now();
  await page.goto(`/projects/${id}`);
  await page.waitForTimeout(25000);
  const txt = await page.evaluate(() => document.body.innerText);
  log.push("--- project page after 25s: loadingGraph=" + /Drawing the graph/.test(txt) + " loadingVersions=" + /Loading versions/.test(txt) + " hasFirst=" + /First/.test(txt));
  await page.screenshot({ path: `${OUT}/net-project.png` });
  log.push("--- editor");
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.goto(`/projects/${id}/edit`);
  await page.waitForTimeout(25000);
  const t2 = await page.evaluate(() => document.body.innerText);
  log.push("editor history loading=" + /Loading version history/.test(t2) + " hasFirst=" + /First/.test(t2));
  await page.screenshot({ path: `${OUT}/net-editor.png` });
  fs.writeFileSync(`${OUT}/net.txt`, log.join("\n"));
  await cleanupE2eUsers("run").catch(() => {});
});
